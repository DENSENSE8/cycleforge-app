/** One `<use>` node against the sprite {@link ShellIconSprite} mounts once. */
export function Icon({ name, size = 14 }: { name: IconName; size?: number }) {
  return (
    <svg width={size} height={size} aria-hidden focusable="false">
      <use href={`#icon-${name}`} />
    </svg>
  );
}

